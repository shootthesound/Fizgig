"""
Dataset configuration utilities for Fizgig (image-only, Klein 9B).

Reads TOML config files, validates them with voluptuous, and produces
Blueprint objects that drive dataset construction.

TOML format (generated by the Fizgig GUI):

    [general]
    resolution = [992, 992]
    caption_extension = ".txt"
    batch_size = 1
    num_repeats = 1
    enable_bucket = true
    bucket_no_upscale = true

    [[datasets]]
    image_directory = "path/to/images"
    cache_directory = "path/to/cache"

    [[datasets]]                      # optional regularisation set
    image_directory = "path/to/reg"
    cache_directory = "path/to/reg_cache"
    is_reg = true
"""

import argparse
import functools
import logging
import random
from dataclasses import asdict, dataclass
from pathlib import Path
from textwrap import dedent, indent
from typing import List, Optional, Sequence, Tuple, Union, TYPE_CHECKING

if TYPE_CHECKING:
    from multiprocessing.sharedctypes import Synchronized

SharedEpoch = Optional["Synchronized[int]"]

import toml
import voluptuous
from voluptuous import Any, ExactSequence, MultipleInvalid, Object, Schema

from fizgig.dataset.image_dataset import DatasetGroup, ImageDataset

logger = logging.getLogger(__name__)
logging.basicConfig(level=logging.INFO)


# ---------------------------------------------------------------------------
# Dataclasses
# ---------------------------------------------------------------------------


@dataclass
class BaseDatasetParams:
    """Common parameters shared across all dataset entries."""

    resolution: Tuple[int, int] = (960, 544)
    enable_bucket: bool = False
    bucket_no_upscale: bool = False
    caption_extension: Optional[str] = None
    batch_size: int = 1
    num_repeats: int = 1
    cache_directory: Optional[str] = None
    debug_dataset: bool = False
    architecture: str = "no_default"
    clip_megapixels: Optional[float] = None


@dataclass
class ImageDatasetParams(BaseDatasetParams):
    """Image-specific parameters."""

    image_directory: Optional[str] = None
    control_directory: Optional[str] = None
    # a multi-picture edit's extra pictures (photo_1, photo_2 ... for photo.png), beside control_directory's originals
    extra_reference_directory: Optional[str] = None
    # Regularisation set: trained at a fixed reduced LR and exempt from the loss watch.
    # A prior anchor, not a subject — see the trainer's reg handling.
    is_reg: bool = False
    # Caption rewrites applied as each caption is read, the user's .txt files untouched: [[from, to], ...], whole
    # words, case-insensitive, in order (multi-person mode fuses "zwxem, a woman" into "zwxemwoman")
    caption_replace: Optional[list] = None
    # Photos only: a family that trains clips or voice globs neither from this folder (Fizgig LoRA Isolation on
    # MiniMax H3 trains people from their stills)
    photos_only: bool = False
    # Masked training: where the pictures' masks are when not beside them (a training share's helper, sent the cache)
    mask_directory: Optional[str] = None
    # The pictures' training-key prefix (ImageDataset.item_prefix): a sub-folder's path, or another folder's tag
    item_prefix: str = ""


@dataclass
class DatasetBlueprint:
    params: ImageDatasetParams


@dataclass
class DatasetGroupBlueprint:
    datasets: Sequence[DatasetBlueprint]


@dataclass
class Blueprint:
    dataset_group: DatasetGroupBlueprint


# ---------------------------------------------------------------------------
# Config sanitizer (voluptuous-based TOML validation)
# ---------------------------------------------------------------------------


class ConfigSanitizer:
    """Validates and normalises user-supplied TOML config."""

    @staticmethod
    def __validate_and_convert_twodim(klass, value: Sequence) -> Tuple:
        Schema(ExactSequence([klass, klass]))(value)
        return tuple(value)

    @staticmethod
    def __validate_and_convert_scalar_or_twodim(
        klass, value: Union[float, Sequence]
    ) -> Tuple:
        Schema(Any(klass, ExactSequence([klass, klass])))(value)
        try:
            Schema(klass)(value)
            return (value, value)
        except Exception:
            return ConfigSanitizer.__validate_and_convert_twodim(klass, value)

    # Fields that can appear in both [general] and [[datasets]]
    DATASET_ASCENDABLE_SCHEMA = {
        "caption_extension": str,
        "batch_size": int,
        "num_repeats": int,
        "resolution": functools.partial(
            __validate_and_convert_scalar_or_twodim.__func__, int
        ),
        "enable_bucket": bool,
        "bucket_no_upscale": bool,
        # MiniMax H3: clips are cached and trained at this size or smaller, photos at resolution
        "clip_megapixels": Any(int, float),
    }

    # Fields specific to an image dataset entry
    IMAGE_DATASET_DISTINCT_SCHEMA = {
        "image_directory": str,
        "cache_directory": str,
        "control_directory": str,
        "extra_reference_directory": str,
        "is_reg": bool,
        "caption_replace": [[str]],
        "photos_only": bool,
        "mask_directory": str,
        "item_prefix": str,
    }

    # Options that come from argparse only (not from user config)
    ARGPARSE_SPECIFIC_SCHEMA = {
        "debug_dataset": bool,
    }

    def __init__(self) -> None:
        self.image_dataset_schema = self.__merge_dict(
            self.DATASET_ASCENDABLE_SCHEMA,
            self.IMAGE_DATASET_DISTINCT_SCHEMA,
        )

        self.general_schema = self.__merge_dict(
            self.DATASET_ASCENDABLE_SCHEMA,
        )

        self.user_config_validator = Schema(
            {
                "general": self.general_schema,
                "datasets": [Schema(self.image_dataset_schema)],
            }
        )

        self.argparse_schema = self.__merge_dict(
            self.ARGPARSE_SPECIFIC_SCHEMA,
        )
        self.argparse_config_validator = Schema(
            Object(self.argparse_schema), extra=voluptuous.ALLOW_EXTRA
        )

    def sanitize_user_config(self, user_config: dict) -> dict:
        try:
            return self.user_config_validator(user_config)
        except MultipleInvalid:
            logger.error("Invalid dataset config file format")
            raise

    def sanitize_argparse_namespace(
        self, argparse_namespace: argparse.Namespace
    ) -> argparse.Namespace:
        try:
            return self.argparse_config_validator(argparse_namespace)
        except MultipleInvalid:
            logger.error("Invalid command-line arguments (possible bug)")
            raise

    @staticmethod
    def __merge_dict(*dict_list: dict) -> dict:
        merged = {}
        for schema in dict_list:
            for k, v in schema.items():
                merged[k] = v
        return merged


# ---------------------------------------------------------------------------
# Blueprint generator
# ---------------------------------------------------------------------------


class BlueprintGenerator:
    """Generates a Blueprint by merging TOML config, argparse args, and
    runtime parameters with proper fallback order."""

    BLUEPRINT_PARAM_NAME_TO_CONFIG_OPTNAME: dict = {}

    def __init__(self, sanitizer: ConfigSanitizer):
        self.sanitizer = sanitizer

    def generate(
        self,
        user_config: dict,
        argparse_namespace: argparse.Namespace,
        **runtime_params,
    ) -> Blueprint:
        sanitized_user_config = self.sanitizer.sanitize_user_config(user_config)
        sanitized_argparse_namespace = self.sanitizer.sanitize_argparse_namespace(
            argparse_namespace
        )

        argparse_config = {
            k: v
            for k, v in vars(sanitized_argparse_namespace).items()
            if v is not None
        }
        general_config = sanitized_user_config.get("general", {})

        dataset_blueprints: List[DatasetBlueprint] = []
        for dataset_config in sanitized_user_config.get("datasets", []):
            params = self.generate_params_by_fallbacks(
                ImageDatasetParams,
                [dataset_config, general_config, argparse_config, runtime_params],
            )
            dataset_blueprints.append(DatasetBlueprint(params))

        dataset_group_blueprint = DatasetGroupBlueprint(dataset_blueprints)
        return Blueprint(dataset_group_blueprint)

    @staticmethod
    def generate_params_by_fallbacks(
        param_klass, fallbacks: Sequence[dict]
    ):
        name_map = BlueprintGenerator.BLUEPRINT_PARAM_NAME_TO_CONFIG_OPTNAME
        search_value = BlueprintGenerator.search_value
        default_params = asdict(param_klass())
        param_names = default_params.keys()

        params = {
            name: search_value(
                name_map.get(name, name), fallbacks, default_params.get(name)
            )
            for name in param_names
        }
        return param_klass(**params)

    @staticmethod
    def search_value(key: str, fallbacks: Sequence[dict], default_value=None):
        for cand in fallbacks:
            value = cand.get(key)
            if value is not None:
                return value
        return default_value


# ---------------------------------------------------------------------------
# Dataset group construction
# ---------------------------------------------------------------------------


def generate_dataset_group_by_blueprint(
    dataset_group_blueprint: DatasetGroupBlueprint,
    training: bool = False,
    num_timestep_buckets: Optional[int] = None,
    shared_epoch: SharedEpoch = None,
) -> DatasetGroup:
    """Create a DatasetGroup from a blueprint.

    When *training* is True the datasets are prepared for training (buckets,
    repeats, etc.).  Otherwise they are set up for caching only.
    """
    datasets: List[ImageDataset] = []

    for dataset_blueprint in dataset_group_blueprint.datasets:
        dataset = ImageDataset(**asdict(dataset_blueprint.params))
        datasets.append(dataset)

    # Ensure cache directories are unique across datasets
    cache_directories = [ds.cache_directory for ds in datasets]
    if len(set(cache_directories)) != len(cache_directories):
        raise ValueError(
            "cache_directory must be unique for each dataset "
            "(defaults to image_directory when not specified)"
        )

    # Log dataset info
    info = ""
    for i, dataset in enumerate(datasets):
        info += dedent(
            f"""\
      [Dataset {i}]
        resolution: {dataset.resolution}
        clip_megapixels: {dataset.clip_megapixels}
        batch_size: {dataset.batch_size}
        num_repeats: {dataset.num_repeats}
        caption_extension: "{dataset.caption_extension}"
        enable_bucket: {dataset.enable_bucket}
        bucket_no_upscale: {dataset.bucket_no_upscale}
        cache_directory: "{dataset.cache_directory}"
        debug_dataset: {dataset.debug_dataset}
    """
        )
        info += indent(
            dedent(
                f"""\
        image_directory: "{dataset.image_directory}"
        control_directory: "{dataset.control_directory}"
    \n"""
            ),
            "    ",
        )
    logger.info(f"{info}")

    # Set up buckets and seeding
    seed = random.randint(0, 2**31)  # actual seed is seed + epoch_no
    for dataset in datasets:
        dataset.set_seed(seed, shared_epoch)
        if training:
            dataset.prepare_for_training(num_timestep_buckets=num_timestep_buckets)

    return DatasetGroup(datasets)


# ---------------------------------------------------------------------------
# Config file loading
# ---------------------------------------------------------------------------


def load_user_config(file: str) -> dict:
    """Load a TOML (or JSON) dataset config file and return its contents."""
    path = Path(file)
    if not path.is_file():
        raise ValueError(f"Config file not found: {path}")

    if path.suffix.lower() == ".json":
        import json

        try:
            with open(path, "r", encoding="utf-8") as f:
                config = json.load(f)
        except Exception:
            logger.error(f"Failed to parse JSON config: {path}")
            raise
    elif path.suffix.lower() == ".toml":
        try:
            config = toml.load(path)
        except Exception:
            logger.error(f"Failed to parse TOML config: {path}")
            raise
    else:
        raise ValueError(f"Unsupported config file format: {path}")

    return config


